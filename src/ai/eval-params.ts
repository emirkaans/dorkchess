// Evaluation parameters (centipawns). Hand-set starting values (PeSTO
// piece-square tables and common weights); scripts/tune.ts rewrites this file
// after tuning on self-play positions. Material comes from each variant's
// pieceValues and is not tuned here.

export interface EvalParams {
  tempo: number;
  bishopPair: [number, number];
  doubledPawn: [number, number];
  isolatedPawn: [number, number];
  /** Passed pawn bonus by relative rank (0..7). */
  passedMg: number[];
  passedEg: number[];
  rookOpenFile: [number, number];
  rookSemiOpenFile: [number, number];
  /** Per reachable square beyond the type's average (mid-game, end-game). */
  mobility: Record<string, [number, number]>;
  mobilityBase: Record<string, number>;
  /** Missing pawn in front of a king on its back ranks (mid-game only). */
  kingShieldMissing: number;
  /** King attack (mid-game): per attacked square next to the enemy king, by attacker type. */
  kingAttack: Record<string, number>;
  /** Percentage of the king attack counted, by number of attacking pieces (0..7+); not tuned. */
  kingAttackScale: number[];
  /** Bonus per enemy piece (not pawn or king) attacked by one of our pawns (mid-game, end-game). */
  threatByPawn: [number, number];
  /** Piece-square tables, White's view, rank 8 first. */
  pstMg: Record<string, number[]>;
  pstEg: Record<string, number[]>;
}

