// Draws the link-preview assets ahead of time (they need real font and SVG
// rendering, which the Worker does not have):
//   npm run og-assets  ->  server/og-assets.ts  (frame + piece pictures, packed)
//                          public/og.png        (the site's default preview: the start position)
// Fonts in scripts/og-assets/ (Permanent Marker: Apache 2.0; Oswald and the
// chess glyphs of Noto Sans Symbols 2: OFL).

import { writeFileSync } from 'node:fs';
import { deflateSync } from 'node:zlib';
import { Resvg } from '@resvg/resvg-js';
import { createGame, listVariants } from '../src/engine/index.ts';
import type { Color } from '../src/engine/index.ts';
import { BOARD_X, BOARD_Y, OG_H, OG_W, SQ, composeBoard, encodePng } from '../server/og-image.ts';
import type { OgAssets } from '../server/og-image.ts';

const FONTS = [
  'scripts/og-assets/PermanentMarker-Regular.ttf',
  'scripts/og-assets/Oswald.ttf',
  'scripts/og-assets/chess-glyphs.ttf',
];

function render(svg: string): { pixels: Uint8Array; width: number; height: number } {
  const r = new Resvg(svg, { font: { fontFiles: FONTS, loadSystemFonts: false, defaultFontFamily: 'Oswald' } });
  const img = r.render();
  return { pixels: new Uint8Array(img.pixels), width: img.width, height: img.height };
}

// --- the frame: dark ground, board border, logo and lines on the right ---

const CROWN = 'M6 30L4 8L15 19L24 4L33 19L44 8L42 30Z M8 36H40';
const boardSize = 8 * SQ;
const frameSvg = `<svg xmlns="http://www.w3.org/2000/svg" width="${OG_W}" height="${OG_H}" viewBox="0 0 ${OG_W} ${OG_H}">
  <rect width="${OG_W}" height="${OG_H}" fill="#0a0a0b"/>
  <rect x="${BOARD_X - 10}" y="${BOARD_Y - 10}" width="${boardSize + 20}" height="${boardSize + 20}" rx="6" fill="#111113" stroke="#2a2a2e" stroke-width="2"/>
  <circle cx="${BOARD_X - 4}" cy="${BOARD_Y - 6}" r="16" fill="#ff2e93" opacity="0.85"/>
  <circle cx="${BOARD_X + 22}" cy="${BOARD_Y - 22}" r="5" fill="#ff2e93" opacity="0.85"/>
  <circle cx="${BOARD_X + boardSize + 6}" cy="${BOARD_Y + boardSize + 4}" r="12" fill="#c6ff3d" opacity="0.8"/>
  <g transform="translate(655 150) scale(2.6)" fill="none" stroke="#ff2e93" stroke-width="3.6" stroke-linejoin="round" stroke-linecap="round">
    <path d="${CROWN}"/>
  </g>
  <text x="655" y="330" font-family="Permanent Marker" font-size="112" fill="#ff2e93">PUNK</text>
  <text x="655" y="440" font-family="Permanent Marker" font-size="112" fill="#f1eee8">CHESS</text>
  <g transform="rotate(-4 660 500)">
    <rect x="650" y="470" width="430" height="58" fill="#c6ff3d"/>
    <text x="670" y="512" font-family="Oswald" font-weight="700" font-size="34" fill="#0a0a0b">AYNI OYUN. FARKLI TAVIR.</text>
  </g>
  <text x="655" y="${OG_H - 40}" font-family="Oswald" font-weight="700" font-size="26" fill="#a3a0a8" letter-spacing="2">PUNKCHESS.COM</text>
</svg>`;

const frameRgba = render(frameSvg).pixels;
const frame = new Uint8Array(OG_W * OG_H * 3);
for (let i = 0, j = 0; i < frameRgba.length; i += 4, j += 3) {
  frame[j] = frameRgba[i];
  frame[j + 1] = frameRgba[i + 1];
  frame[j + 2] = frameRgba[i + 2];
}

// --- piece pictures: every piece of every variant, both colours (punk style) ---

const GLYPH_STYLE: Record<Color, { fill: string; stroke: string }> = {
  w: { fill: '#e9e4d8', stroke: '#111111' },
  b: { fill: '#18181b', stroke: '#ff2e93' },
};

function pieceSvg(icon: { kind: 'glyph'; glyph: string } | { kind: 'svg'; svg: (c: Color) => string }, c: Color) {
  if (icon.kind === 'glyph') {
    const glyph = icon.glyph.replace('︎', '');
    const { fill, stroke } = GLYPH_STYLE[c];
    // The UI draws glyphs at 80% of the square.
    return `<svg xmlns="http://www.w3.org/2000/svg" width="${SQ}" height="${SQ}" viewBox="0 0 ${SQ} ${SQ}">
      <text x="${SQ / 2}" y="${SQ * 0.82}" text-anchor="middle" font-family="Noto Sans Symbols 2" font-size="${SQ * 0.8}"
        fill="${fill}" stroke="${stroke}" stroke-width="2.2" stroke-linejoin="round" paint-order="stroke">${glyph}</text>
    </svg>`;
  }
  // SVG icons fill 84% of the square, centred.
  const inner = icon.svg(c).trim();
  const size = SQ * 0.84;
  const off = (SQ - size) / 2;
  const nested = inner.replace('<svg ', `<svg x="${off}" y="${off}" width="${size}" height="${size}" `);
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${SQ}" height="${SQ}" viewBox="0 0 ${SQ} ${SQ}">${nested}</svg>`;
}

const sprites: Record<string, Uint8Array> = {};
for (const v of listVariants()) {
  for (const def of Object.values(v.pieces)) {
    for (const c of ['w', 'b'] as const) {
      const key = c + def.type;
      if (sprites[key]) continue;
      sprites[key] = render(pieceSvg(def.icon, c)).pixels;
    }
  }
}

// --- write the packed assets and the default preview ---

const pack = (data: Uint8Array) => deflateSync(data, { level: 9 }).toString('base64');
const lines = [
  '// Generated by scripts/make-og-assets.ts (npm run og-assets): do not edit.',
  '// Link-preview frame (RGB) and piece pictures (RGBA), deflated and base64-encoded.',
  '',
  `export const FRAME = '${pack(frame)}';`,
  '',
  'export const SPRITES: Readonly<Record<string, string>> = {',
  ...Object.entries(sprites).map(([k, v]) => `  ${k}: '${pack(v)}',`),
  '};',
  '',
];
writeFileSync('server/og-assets.ts', lines.join('\n'));
console.log(`server/og-assets.ts: ${Object.keys(sprites).length} pieces`);

const assets: OgAssets = { frame, sprites };
const start = createGame(listVariants()[0]).position.board;
const pngBytes = await encodePng(composeBoard(assets, start, null), OG_W, OG_H);
writeFileSync('public/og.png', pngBytes);
console.log(`public/og.png: ${pngBytes.length} bytes`);
